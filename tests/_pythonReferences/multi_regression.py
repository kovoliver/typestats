models = [
    ("2-Variable Model", X_2v, Y_2v),
    ("3-Variable Model", X_3v, Y_3v),
    ("4-Variable Model", X_4v, Y_4v),
    ("5-Variable Model", X_5v, Y_5v)
]

print("========================================================================")
print("STATSMODELS OLS RESULTS (COLUMN-MAJOR FORTRAN LAYOUT)")
print("========================================================================\n")

for title, X_cols, y in models:
    # Oszlopos (Column-Major / Fortran order) mátrix építése:
    # Az N darab megfigyelés alkotja a sorokat, a K darab változó az oszlopokat
    X_matrix = np.array(X_cols, dtype=np.float64).T
    
    # Intercept (konstans 1-esek oszlopa) hozzáadása az elejére
    X_with_intercept = sm.add_constant(X_matrix)
    
    fit = sm.OLS(y, X_with_intercept).fit()
    
    betas = fit.params.tolist()
    rsd = float(np.sqrt(fit.ssr / fit.df_resid))
    f_val = float(fit.fvalue)
    
    print(f"=== {title} ===")
    print(f"Betas (b0, b1...): {betas}")
    print(f"RSD:               {rsd}")
    print(f"F-Value:           {f_val}\n")